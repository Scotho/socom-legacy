/**
 * The Forge's map-still cameras (FP-15, FP.R15: the owner, 2026-11-09 -- "yes the forge should use those as the starting
 * locations"; product track, OT.R53: a Forge start view, the Forge has no original and nothing the game does changes).
 * Reads a folder of Craig's map stills (2026-11-08, taken in the Forge at build c7c4cf31e: one `<MAPID>-<slug>.json` a
 * map, its `mapId` and its `camera` -- `{ x, y, z, yaw, pitch }`, the page's own `cameraNow()`, so `fly.setPose`'s terms
 * -- and a `manifest.json` listing them) and writes `packages/viewer/src/forge/mapStills.ts`: each map id and its camera
 * exactly as the file gives it, unrounded, its file named in a comment. The stills' PNGs are never read.
 *
 *   npx tsx tools/forge-map-stills.ts <stills folder>            (from socomlegacy/) write the table
 *   npx tsx tools/forge-map-stills.ts <stills folder> --check    exit 1 when the committed table differs
 *   (--out <file> writes or checks another file; the tests use it)
 *
 * `tools/test/forgeMapStills.test.ts` checks the committed table against `shared/map-stills` when that folder is in the
 * tree.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const MAP_STILLS_TABLE = join(REPO, 'socomlegacy', 'packages', 'viewer', 'src', 'forge', 'mapStills.ts');

const KEYS = ['x', 'y', 'z', 'yaw', 'pitch'] as const;
export interface StillCamera { x: number; y: number; z: number; yaw: number; pitch: number }
export interface Still { id: string; file: string; camera: StillCamera }

const isObj = (v: unknown): v is Record<string, unknown> => typeof v === 'object' && v !== null && !Array.isArray(v);

/** Every still's camera in the folder, in the manifest's order (else by map number), or a throw naming the file. */
export function readStills(dir: string): Still[] {
  const out: Still[] = [];
  const files = readdirSync(dir).filter((f) => /\.json$/i.test(f) && f.toLowerCase() !== 'manifest.json').sort();
  for (const file of files) {
    const raw: unknown = JSON.parse(readFileSync(join(dir, file), 'utf8'));
    if (!isObj(raw) || typeof raw['mapId'] !== 'string' || !/^MP\d+$/.test(raw['mapId'])) throw new Error(`${file}: no mapId like "MP1"`);
    const cam = raw['camera'];
    if (!isObj(cam)) throw new Error(`${file}: no camera`);
    const camera = {} as StillCamera;
    for (const k of KEYS) {
      const v = cam[k];
      if (typeof v !== 'number' || !Number.isFinite(v)) throw new Error(`${file}: camera.${k} is not a finite number`);
      camera[k] = v;
    }
    const id = raw['mapId'];
    if (out.some((s) => s.id === id)) throw new Error(`${file}: ${id} has a still twice`);
    out.push({ id, file, camera });
  }
  const num = (id: string): number => Number(id.slice(2));
  const manifestPath = join(dir, 'manifest.json');
  if (!existsSync(manifestPath)) return out.sort((a, b) => num(a.id) - num(b.id));
  const manifest: unknown = JSON.parse(readFileSync(manifestPath, 'utf8'));
  const maps = isObj(manifest) && Array.isArray(manifest['maps']) ? manifest['maps'] : null;
  if (!maps) throw new Error('manifest.json: no maps list');
  const order = maps.map((m: unknown) => (isObj(m) && typeof m['stem'] === 'string' ? m['stem'] : ''));
  if (new Set(order).size !== order.length) throw new Error('manifest.json names a map twice');
  for (const id of order) if (!out.some((s) => s.id === id)) throw new Error(`manifest.json names ${id || '(a map with no stem)'}, which has no still`);
  for (const s of out) if (!order.includes(s.id)) throw new Error(`${s.file}: ${s.id} is not in manifest.json`);
  return order.map((id) => out.find((s) => s.id === id)!);
}

/** The table's text: each value as `String(number)` writes it -- the shortest text that reads back as the same double. */
export function renderTable(stills: readonly Still[]): string {
  const rows = stills.map((s) => `  ${s.id}: { ${KEYS.map((k) => `${k}: ${String(s.camera[k])}`).join(', ')} },   // ${s.file}\n`).join('');
  return `/**
 * The Forge's starting camera on a disc map's base (FP-15, FP.R15: the owner, 2026-11-09; product track, a Forge start
 * view -- the Forge has no original, and nothing the game does reads this).
 * Source: Craig's map stills, 2026-11-08, build c7c4cf31e -- each map's \`<MAPID>-<slug>.json\` \`camera\`, the page's
 * own \`cameraNow()\` (\`fly.pose()\`) when the still was taken, so in \`fly.setPose\`'s terms (game units, degrees, the
 * port's yaw), unrounded.
 *
 * GENERATED by \`socomlegacy/tools/forge-map-stills.ts\` -- do not edit by hand; \`--check\` refuses a difference.
 */

/** A still's camera: \`FlyCamera.pose()\`'s fields. */
export interface MapStillCamera { x: number; y: number; z: number; yaw: number; pitch: number }

/** By map id (the archive's stem, \`MP1\`), in the stills' manifest order. */
export const MAP_STILLS: Readonly<Record<string, Readonly<MapStillCamera>>> = {
${rows}};

/** The still's camera for this map id (a copy), or null when the map has none. */
export function mapStill(id: string): MapStillCamera | null {
  return Object.prototype.hasOwnProperty.call(MAP_STILLS, id) ? { ...MAP_STILLS[id]! } : null;
}
`;
}

/** The command: 0 written or matching, 1 a table that differs (or a still refused), 2 no folder named. */
export function main(argv: readonly string[], say: (line: string) => void = (l) => console.log(l)): number {
  const check = argv.includes('--check');
  const outAt = argv.indexOf('--out');
  const out = outAt >= 0 ? argv[outAt + 1] : MAP_STILLS_TABLE;
  const dir = argv.find((a, i) => !a.startsWith('--') && (outAt < 0 || i !== outAt + 1));
  if (!dir || !out) { say('usage: forge-map-stills.ts <stills folder> [--check] [--out <file>]'); return 2; }
  let text: string;
  try { text = renderTable(readStills(dir)); } catch (e) { say(e instanceof Error ? e.message : String(e)); return 1; }
  if (check) {
    const now = existsSync(out) ? readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : null;
    if (now === text) { say(`${out} matches ${dir}`); return 0; }
    say(`${out} differs from what ${dir} gives: run \`npx tsx tools/forge-map-stills.ts <stills folder>\` from socomlegacy/`);
    return 1;
  }
  writeFileSync(out, text);
  say(`wrote ${out}`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) process.exit(main(process.argv.slice(2)));
